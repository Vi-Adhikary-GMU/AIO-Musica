package com.example.aio_musica.mvsep

import com.google.gson.annotations.SerializedName

/**
 * Represents the response returned by MVSEP when an audio separation job
 * is submitted.
 *
 * @property success Indicates whether the request was successfully accepted.
 * @property data Contains information about the submitted job, if available.
 */
data class MvsepCreateResponse(
    @SerializedName("success")
    val success: Boolean,

    @SerializedName("data")
    val data: MvsepJobData?
)

/**
 * Contains information identifying an MVSEP audio separation job.
 *
 * @property hash Unique identifier used to track the separation job.
 * @property link Optional link associated with the submitted job.
 * @property message Optional information or error message returned by the API.
 */
data class MvsepJobData(
    @SerializedName("hash")
    val hash: String?,

    @SerializedName("link")
    val link: String?,

    @SerializedName("message")
    val message: String?
)

/**
 * Represents the response received when checking the status
 * of an MVSEP audio separation job.
 *
 * @property success Indicates whether the status request was successful.
 * @property status Current processing status of the separation job.
 * @property data Contains the separation results when available.
 */
data class MvsepStatusResponse(
    @SerializedName("success")
    val success: Boolean,

    @SerializedName("status")
    val status: String,

    @SerializedName("data")
    val data: MvsepResultData?
)

/**
 * Contains the results returned after an audio separation job.
 *
 * @property message Optional message describing the processing result.
 * @property files List of generated audio stems, if available.
 */
data class MvsepResultData(
    @SerializedName("message")
    val message: String?,

    @SerializedName("files")
    val files: List<MvsepStem>?
)

/**
 * Represents an individual audio stem generated by MVSEP.
 * A stem is an isolated component of an audio track, such as vocals,
 * instrumental, drums, bass, or another separated audio component.
 *
 * @property name Name or category of the generated audio stem.
 * @property url Download URL for the generated audio stem.
 */
data class MvsepStem(
    @SerializedName("name")
    val name: String?,

    @SerializedName("url")
    val url: String?
)